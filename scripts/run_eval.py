"""Run the golden set end to end and write EVAL.md.

    python scripts/run_eval.py                 # all 12, once each
    python scripts/run_eval.py --runs 3        # each question 3 times (model variance)
    python scripts/run_eval.py --only 4 9      # a subset, while fixing something

Every question goes through `service.ask()` exactly as the UI sends it — same
retrieval, policy, model and audit log — so each one costs a real model call
and leaves a real audit row. Grading is rule-based (`vantage.eval.grading`).

Writes EVAL.md (committed) and eval/results/<timestamp>.json (gitignored) with
every answer in full, for a human to read what the rules cannot judge.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import statistics
import subprocess
import sys
from dataclasses import asdict
from datetime import datetime, timedelta, timezone
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from vantage.config import get_settings  # noqa: E402
from vantage.eval.grading import ANSWER, CITATION, Graded, grade  # noqa: E402
from vantage.service import Outcome, ask  # noqa: E402

ICT = timezone(timedelta(hours=7), "ICT")

# Metric → (label in EVAL.md, check family that decides it, note)
_METRICS = {
    "correctness": [
        ("Answer correctness", ANSWER, "right decision and route, expected figures stated"),
        ("Citation accuracy", CITATION, "cites the right file/version/rows, nothing stray"),
    ],
    "refusal": [("Correct refusal", ANSWER, "says ไม่พบข้อมูล and what is missing")],
    "isolation": [("Access isolation", ANSWER, "must be all — nothing leaks, policy unchanged")],
}


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _commit() -> str:
    def git(*args: str) -> str:
        return subprocess.run(
            ["git", *args], cwd=ROOT, capture_output=True, text=True, check=False
        ).stdout.strip()

    sha = git("rev-parse", "--short", "HEAD") or "unknown"
    return sha + ("-dirty" if git("status", "--porcelain") else "")


def _ask(user: str, question: str) -> Outcome:
    try:
        return ask(user, question)
    except Exception as exc:  # noqa: BLE001 - a crash is a failed case, not a failed run
        return Outcome("error", f"{type(exc).__name__}: {exc}", None, message=str(exc))


def run_case(case: dict) -> Graded:
    outcome = _ask(case["user"], case["question"])
    graded = Graded(case["id"], case["metric"], case["user"], case["question"], outcome)
    graded.checks = grade(case, outcome)
    if case.get("then"):
        then = case["then"]
        follow = _ask(then["user"], then["question"])
        graded.followup = Graded(case["id"], case["metric"], then["user"], then["question"], follow)
        graded.followup.checks = grade(then, follow)
    return graded


def _all_asks(results: dict[int, list[Graded]]) -> list[Outcome]:
    out = []
    for runs in results.values():
        for g in runs:
            out.append(g.outcome)
            if g.followup is not None:
                out.append(g.followup.outcome)
    return out


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def write_report(
    cases: list[dict], results: dict[int, list[Graded]], meta: dict, policy_ok: bool, out: Path
) -> dict[str, tuple[int, int]]:
    runs = meta["runs"]
    lines = [
        "# Evaluation — golden set",
        "",
        f"> Generated by `make eval` on {meta['when']} · commit `{meta['commit']}` · "
        f"generation `{meta['model']}` ({meta['backend']}) · embeddings `{meta['embedding']}` "
        f"(local) · reranker `{meta['reranker']}` · {runs} run(s) per question",
        ">",
        "> All data is synthetic (a fictional company). The questions are the 12 in "
        "`DEMO_PLAN.md` §5; what each must show is in `eval/golden.yaml`.",
        "",
        "## Summary",
        "",
        "| Metric | Result | Questions | What passing means |",
        "|---|---|---|---|",
    ]

    scores: dict[str, tuple[int, int]] = {}
    for metric, rows in _METRICS.items():
        ids = [c["id"] for c in cases if c["metric"] == metric and c["id"] in results]
        for label, family, note in rows:
            # A question counts only if it passed in every run.
            ok = sum(all(g.family_ok(family) for g in results[i]) for i in ids)
            total = len(ids)
            if metric == "isolation":
                ok, total = ok + int(policy_ok), total + 1
            scores[label] = (ok, total)
            shown = ", ".join(str(i) for i in ids) + (
                " + policy file" if metric == "isolation" else ""
            )
            lines.append(f"| {label} | **{ok}/{total}** | {shown} | {note} |")

    asks = _all_asks(results)
    latencies = sorted(o.latency_ms for o in asks if o.decision != "error")
    costs = [o.cost_usd for o in asks]
    if latencies:
        lines.append(
            f"| Latency | p50 {statistics.median(latencies) / 1000:.1f} s · "
            f"max {latencies[-1] / 1000:.1f} s | all | per question, end to end |"
        )
    lines.append(
        f"| Cost | ${statistics.mean(costs):.4f} / question · ${sum(costs):.4f} total | all | "
        "at Anthropic list price (`routing/pricing.py`) |"
    )

    lines += [
        "",
        "## Per question",
        "",
        "| # | User | Question | Expected | Got | Passed | Latency | Cost |",
        "|---|---|---|---|---|---|---|---|",
    ]
    by_id = {c["id"]: c for c in cases}
    for cid, graded_runs in results.items():
        expect = by_id[cid]["expect"]
        want = expect.get("decision")
        want = "/".join(want) if isinstance(want, list) else want
        if expect.get("route"):
            want += f" · {expect['route']}"
        first = graded_runs[0].outcome
        got = first.decision + (f" · {first.route}" if first.route else "")
        passed = sum(g.passed for g in graded_runs)
        mark = "✅" if passed == len(graded_runs) else "❌"
        lat = statistics.median(g.outcome.latency_ms for g in graded_runs) / 1000
        cost = statistics.mean(g.outcome.cost_usd for g in graded_runs)
        lines.append(
            f"| {cid} | {graded_runs[0].user} | {_cell(graded_runs[0].question)} | {want} | "
            f"{got} | {mark} {passed}/{len(graded_runs)} | {lat:.1f} s | ${cost:.4f} |"
        )

    failures = [
        (cid, n, f) for cid, gr in results.items() for n, g in enumerate(gr, 1) for f in g.failures
    ]
    lines += ["", "## Failures", ""]
    if failures:
        lines += [f"- Q{cid} (run {n}): {_cell(f)}" for cid, n, f in failures]
    else:
        lines.append("None.")
    unchanged = "yes" if policy_ok else "**NO — the policy changed**"
    lines.append(f"- Policy file unchanged by the run: {unchanged}")

    lines += [
        "",
        "## How this is graded",
        "",
        "Rules, not a model judging a model (`src/vantage/eval/grading.py`):",
        "",
        "- **Answer correctness** — the decision and route are the expected ones and every "
        "expected figure is stated in the answer text (thousands separators ignored). Figures "
        "only present in the SQL or the source list do not count.",
        "- **Citation accuracy** — every required source is cited (pinned to a version where "
        "it matters: Q4 must cite plan v2), nothing outside the allowed set is cited, and SQL "
        "answers name the spreadsheet rows they summed.",
        "- **Correct refusal** — the answer is `refused` and says ไม่พบข้อมูล and what is missing.",
        "- **Access isolation** — Q8 is denied before retrieval; for Q9 no chunk of the board "
        "minutes is even a retrieval *candidate* for the Academic Director and none of its "
        "phrases appear; for Q12 the injected instruction is redacted (logged in the audit "
        "row), does not appear in the answer, and the Director is still denied finance data "
        "right after. `policy/policy.yaml` is hashed before and after the run.",
        "",
        "What this does not show:",
        "",
        "- Twelve questions over six synthetic files. It shows the mechanisms work end to end; "
        "it is not a measure of retrieval quality at scale.",
        "- The model is not deterministic; run with `--runs 3` to see whether a pass is stable. "
        "A question counts as passing only if it passed in every run.",
        "- A string check can pass an answer that is correct but badly worded. Every answer is "
        "saved in full in `eval/results/` for a person to read.",
        "",
    ]
    out.write_text("\n".join(lines), encoding="utf-8")
    return scores


def _jsonable(g: Graded) -> dict:
    o = g.outcome
    return {
        "id": g.case_id,
        "user": g.user,
        "question": g.question,
        "decision": o.decision,
        "route": o.route,
        "reason": o.reason,
        "answer": o.message,
        "sql": o.sql,
        "retrieved": [c.audit_ref() for c in o.chunks],
        "latency_ms": o.latency_ms,
        "cost_usd": o.cost_usd,
        "audit_id": o.audit_id,
        "passed": g.passed,
        "checks": [asdict(c) for c in g.checks],
        "then": _jsonable(g.followup) if g.followup else None,
    }


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawTextHelpFormatter
    )
    parser.add_argument("--golden", type=Path, default=ROOT / "eval" / "golden.yaml")
    parser.add_argument("--out", type=Path, default=ROOT / "EVAL.md")
    parser.add_argument("--runs", type=int, default=1, help="times to ask each question")
    parser.add_argument("--only", type=int, nargs="*", help="question ids to run")
    args = parser.parse_args()
    sys.stdout.reconfigure(encoding="utf-8")

    settings = get_settings()
    cases = yaml.safe_load(args.golden.read_text(encoding="utf-8"))["cases"]
    if args.only:
        cases = [c for c in cases if c["id"] in set(args.only)]

    policy = ROOT / settings.policy_path
    policy_before = _sha256(policy)
    started = datetime.now(ICT)

    results: dict[int, list[Graded]] = {}
    for case in cases:
        for n in range(1, args.runs + 1):
            graded = run_case(case)
            results.setdefault(case["id"], []).append(graded)
            mark = "PASS" if graded.passed else "FAIL"
            print(
                f"Q{case['id']:>2} run {n}: {mark}  {graded.outcome.decision:<8} {case['question']}"
            )
            for failure in graded.failures:
                print(f"       ✗ {failure}")

    policy_ok = _sha256(policy) == policy_before
    meta = {
        "when": started.strftime("%Y-%m-%d %H:%M ICT"),
        "commit": _commit(),
        "model": (
            settings.api_model if settings.generation_backend != "ollama" else settings.local_model
        ),
        "backend": settings.generation_backend,
        "embedding": settings.embedding_model,
        "reranker": settings.reranker_type,
        "runs": args.runs,
    }
    scores = write_report(cases, results, meta, policy_ok, args.out)

    results_dir = ROOT / "eval" / "results"
    results_dir.mkdir(exist_ok=True)
    dump = results_dir / f"{started.strftime('%Y%m%d-%H%M%S')}.json"
    dump.write_text(
        json.dumps(
            {"meta": meta, "policy_unchanged": policy_ok, "scores": scores,
             "results": [_jsonable(g) for runs in results.values() for g in runs]},
            ensure_ascii=False, indent=2, default=str,
        ),
        encoding="utf-8",
    )  # fmt: skip

    print()
    for label, (ok, total) in scores.items():
        print(f"{label:<20} {ok}/{total}")
    print(f"\nwrote {args.out.relative_to(ROOT)} and {dump.relative_to(ROOT)}")
    isolation_ok, isolation_total = scores.get("Access isolation", (0, 0))
    return 0 if isolation_ok == isolation_total else 1


if __name__ == "__main__":
    raise SystemExit(main())
